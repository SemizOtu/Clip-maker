const pad = (n) => String(n).padStart(2, '0');
export const ymd = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;

// Tarihin gün numarası (yerel takvim)
const dayNo = (d) => Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 86_400_000);

// O günün sorusu; Deniz kendi sorularını eklediyse onlar da sıraya girer
export function questionFor(date = new Date(), extra = []) {
  const list = [...(Array.isArray(extra) ? extra.filter((q) => String(q || '').trim()) : []), ...QUESTIONS];
  return String(list[((dayNo(date) % list.length) + list.length) % list.length]).trim();
}
